#!/usr/bin/env bash
# Refresh Cloudflare's address ranges. Run it now and then (they change about once a year), then reload Caddy:
#     sudo deploy/update-cloudflare-ips.sh && sudo systemctl reload caddy
# Writes deploy/cloudflare.caddy and prints the matching firewall rules. Nothing else is touched.
# Override the sources with CF_V4_URL / CF_V6_URL (tests use file:// URLs).
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
v4="${CF_V4_URL:-https://www.cloudflare.com/ips-v4}"
v6="${CF_V6_URL:-https://www.cloudflare.com/ips-v6}"
tmp="$(mktemp)"; trap 'rm -f "$tmp"' EXIT
list="$( { curl -fsS --max-time 20 "$v4"; echo; curl -fsS --max-time 20 "$v6"; echo; } | tr -d '\r' | grep -E '^[0-9a-fA-F:.]+/[0-9]+$' || true)"
count="$(printf '%s\n' "$list" | grep -c . || true)"
if [ "$count" -lt 10 ]; then echo "refusing to write: only $count ranges downloaded" >&2; exit 1; fi
{
  echo "# Generated by deploy/update-cloudflare-ips.sh from $v4 and $v6."
  echo "# Imported by the global options block of the Caddyfile (see the comment at its top)."
  echo "servers {"
  printf '\ttrusted_proxies static %s\n' "$(printf '%s\n' "$list" | tr '\n' ' ' | sed 's/ *$//')"
  echo "	client_ip_headers CF-Connecting-IP"
  echo "}"
} > "$tmp"
install -m 0644 "$tmp" "$here/cloudflare.caddy"
echo "wrote $here/cloudflare.caddy ($count ranges)"
echo
echo "# Firewall (ufw): let only Cloudflare reach the web ports, then remove any broader 80/443 rule:"
printf '%s\n' "$list" | while read -r net; do echo "sudo ufw allow from $net to any port 80,443 proto tcp"; done
